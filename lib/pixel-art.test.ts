import { describe, expect, it } from "vitest";
import { biteCells, dishScale, drawEmptyPlate, drawHomeScene, emptyPlateScale, MIN_EMPTY_PLATE_PX, drawSprite, HEAD_ANCHOR, homeSceneCell, SPRITE_SIZE } from "./pixel-art";
import { ACCESSORIES, MONSTERS } from "./monster-catalog";
import type { SpriteKind } from "./sprite-kind";

// A stand-in canvas: drawHomeScene only sets width/height and asks for a 2D context, and returns
// early (no pixels flushed) when there is none, so the layout can be checked without a browser.
const fakeCanvas = () => ({ width: 0, height: 0, getContext: () => null }) as unknown as HTMLCanvasElement;

describe("homeSceneCell", () => {
  it("is a whole number between 4 and 7, so pixels stay square", () => {
    for (const [w, h] of [[320, 568], [390, 844], [820, 1180], [1440, 900], [1920, 800], [3840, 2160]]) {
      const c = homeSceneCell(w, h);
      expect(Number.isInteger(c)).toBe(true);
      expect(c).toBeGreaterThanOrEqual(4);
      expect(c).toBeLessThanOrEqual(7);
    }
  });

  it("is chunkier on a laptop than on a phone", () => {
    expect(homeSceneCell(390, 844)).toBe(5);
    expect(homeSceneCell(1440, 900)).toBe(7);
  });
});

describe("drawHomeScene", () => {
  it.each([[78, 169], [206, 129], [275, 115], [117, 169], [40, 40]])("fits a %i×%i grid and hangs one torch on each side wall", (W, H) => {
    const cv = fakeCanvas();
    const { torches } = drawHomeScene(cv, W, H);
    expect([cv.width, cv.height]).toEqual([W, H]);
    expect(torches).toHaveLength(2);
    for (const t of torches) {
      expect(t.x).toBeGreaterThan(0);
      expect(t.x).toBeLessThan(W);
      expect(t.y).toBeGreaterThan(0);
      expect(t.y).toBeLessThan(H);
    }
    expect(torches[0].x).toBeLessThan(W / 2);
    expect(torches[1].x).toBeGreaterThan(W / 2);
  });

  it("is seeded, so the same size always gives the same scene", () => {
    expect(drawHomeScene(fakeCanvas(), 120, 90)).toEqual(drawHomeScene(fakeCanvas(), 120, 90));
  });
});

// Generated by /ship coverage audit.
// Value: protects=each sprite draws at the size SPRITE_SIZE says (Sprite and DishOnStage size their box from it);
// fails_when=a sprite's Px dims drift from its SPRITE_SIZE row, as the new pot, smoke and dishes could; why_new=no
// test drew sprites; seam=none; no_claim=what the pixels look like (no 2D context in node)
describe("drawSprite", () => {
  it("draws every sprite, in every frame, at its SPRITE_SIZE", () => {
    for (const [kind, [w, h]] of Object.entries(SPRITE_SIZE) as [SpriteKind, [number, number]][]) {
      for (const variant of [0, 1]) {
        const cv = fakeCanvas();
        drawSprite(cv, kind, variant);
        expect([kind, cv.width, cv.height]).toEqual([kind, w, h]);
      }
    }
  });
});

describe("hats on a repeat appearance (docs/designs/monster-catalog.md §3)", () => {
  // Value: protects=every hat, anchored on every room monster's head, stays inside the monster's canvas, and is 8–11 cells wide (R5); fails_when=an anchor or a hat grid grows past the canvas; why_new=new sprites; seam=none; no_claim=how good they look (PNG review)
  it("fits every hat on every room monster", () => {
    for (const m of MONSTERS.filter((x) => !x.boss)) {
      const [mw, mh] = SPRITE_SIZE[m.sprite];
      const [ax, ay] = HEAD_ANCHOR[m.sprite];
      for (const a of ACCESSORIES) {
        const [w, h] = SPRITE_SIZE[`acc-${a}`];
        expect(w, a).toBeGreaterThanOrEqual(8);
        expect(w, a).toBeLessThanOrEqual(11);
        const left = ax - Math.floor(w / 2);
        const top = ay - h + 1;
        expect(left >= 0 && top >= 0 && left + w <= mw && ay <= mh - 1, `${a} on ${m.sprite}`).toBe(true);
      }
    }
  });
});

// Value: protects=the three bites eat the food and never the plate, every bitten edge is outlined, and no bite adds a
// cell (docs/designs/eat-dish.md eng F2); fails_when=the bite circles move onto the plate, the gap is left unoutlined, a
// bite eats nothing, or 0 bites changes the dish; why_new=new feature; seam=a canvas stand-in that keeps the pixels
// Px.flush writes; no_claim=how good the bites look (the 25-dish PNG review in the PR)
describe("biteCells", () => {
  /** Draw a sprite and keep its RGBA, without a browser. */
  const pixels = (kind: SpriteKind) => {
    let data: Uint8ClampedArray = new Uint8ClampedArray(0);
    const ctx = { createImageData: (w: number, h: number) => ({ data: new Uint8ClampedArray(w * h * 4) }), putImageData: (img: { data: Uint8ClampedArray }) => (data = img.data) };
    const cv = { width: 0, height: 0, getContext: () => ctx } as unknown as HTMLCanvasElement;
    drawSprite(cv, kind);
    return { data, w: cv.width, h: cv.height };
  };
  const opaque = (d: Uint8ClampedArray) => d.filter((v, i) => i % 4 === 3 && v > 0).length;
  const rgbAt = (d: Uint8ClampedArray, i: number) => `${d[i]},${d[i + 1]},${d[i + 2]}`;
  const dishes = Object.keys(SPRITE_SIZE).filter((k) => k.startsWith("dish-")) as SpriteKind[];

  it("0 bites leaves the dish as it was", () => {
    const { data, w, h } = pixels("dish-jelly");
    expect(biteCells(data, w, h, 0)).toEqual(data);
  });

  it.each(dishes)("%s: each bite eats more, the gap is outlined, the plate stays", (kind) => {
    const { data, w, h } = pixels(kind);
    let prev = opaque(data);
    for (const n of [1, 2, 3]) {
      const out = biteCells(data, w, h, n);
      const left = opaque(out);
      expect(left, `${kind} bite ${n}`).toBeLessThan(prev);
      prev = left;
      for (let i = 0; i < out.length; i += 4) {
        // Nothing appears: a cell is only ever cleared or outlined.
        if (!data[i + 3]) expect(out[i + 3]).toBe(0);
        if (!data[i + 3] || out[i + 3]) continue;
        // The plate's shade (#d8c8a8) is never eaten.
        expect(rgbAt(data, i)).not.toBe("216,200,168");
        // A cleared cell's opaque neighbours are outlined.
        const x = (i / 4) % w;
        for (const [j, nx] of [[i - 4, x - 1], [i + 4, x + 1], [i - w * 4, x], [i + w * 4, x]])
          if (j >= 0 && j < out.length && nx >= 0 && nx < w && out[j + 3]) expect(rgbAt(out, j)).toBe("42,21,51");
      }
    }
  });

  // Value: protects=the retro design review fixes (P2-3, P2-5): the first bite reads from afar, and the steam stops at the
  // third bite while a highlight on the food stays; fails_when=the first bite shrinks back to a notch, steam outlives bite 3
  // or goes early; why_new=retro fix; seam=the same canvas stand-in; no_claim=how the bites look (the PR's contact sheet)
  /** White cells in the open (no opaque cell beside them): the steam's diagonal wisps (`steam()` in pixel-art.ts). */
  const steamCells = (d: Uint8ClampedArray, w: number) => {
    const filled = (j: number) => j >= 0 && j < d.length && d[j + 3] > 0;
    let n = 0;
    for (let i = 0; i < d.length; i += 4) {
      const x = (i / 4) % w;
      if (d[i + 3] && rgbAt(d, i) === "255,255,255" && !((x > 0 && filled(i - 4)) || (x < w - 1 && filled(i + 4)) || filled(i - w * 4) || filled(i + w * 4))) n++;
    }
    return n;
  };
  it.each(dishes)("%s: the first bite is about as big as the second, and the steam goes at the third", (kind) => {
    const { data, w, h } = pixels(kind);
    const [b1, b2] = [1, 2].map((n) => biteCells(data, w, h, n));
    expect(opaque(data) - opaque(b1)).toBeGreaterThanOrEqual(0.7 * (opaque(b1) - opaque(b2)));
    if (steamCells(data, w)) expect(steamCells(b2, w), `${kind} steam at bite 2`).toBeGreaterThan(0);
    expect(steamCells(biteCells(data, w, h, 3), w)).toBe(0);
  });
  it("a steaming dish keeps all its steam for two bites", () => {
    const { data, w, h } = pixels("dish-skewer");
    expect(steamCells(data, w)).toBe(12); // three wisps of four
    expect(steamCells(biteCells(data, w, h, 2), w)).toBe(12);
  });
});

// Value: protects=the empty plate is the dish's own plate on the dish's own canvas, so the last cut only takes the food
// (retro design review P2-2); fails_when=PLATE_AT drifts from a dish's plate() call, or the empty plate changes size;
// why_new=retro fix; seam=a canvas stand-in that keeps the pixels Px.flush writes; no_claim=how the crumbs look
describe("drawEmptyPlate", () => {
  const pixels = (kind: SpriteKind, draw: (cv: HTMLCanvasElement, kind: SpriteKind) => void) => {
    let data: Uint8ClampedArray = new Uint8ClampedArray(0);
    const ctx = { createImageData: (w: number, h: number) => ({ data: new Uint8ClampedArray(w * h * 4) }), putImageData: (img: { data: Uint8ClampedArray }) => (data = img.data) };
    const cv = { width: 0, height: 0, getContext: () => ctx } as unknown as HTMLCanvasElement;
    draw(cv, kind);
    return { data, w: cv.width, h: cv.height };
  };
  const dishes = Object.keys(SPRITE_SIZE).filter((k) => k.startsWith("dish-")) as SpriteKind[];
  const SHADE = [216, 200, 168];
  const shadeAt = (d: Uint8ClampedArray, i: number) => d[i + 3] > 0 && d[i] === SHADE[0] && d[i + 1] === SHADE[1] && d[i + 2] === SHADE[2];

  it.each(dishes)("%s: the same canvas, and every plate shade cell of the dish is still there", (kind) => {
    const dish = pixels(kind, (cv, k) => drawSprite(cv, k));
    const empty = pixels(kind, drawEmptyPlate);
    expect([empty.w, empty.h]).toEqual([dish.w, dish.h]);
    for (let i = 0; i < dish.data.length; i += 4) if (shadeAt(dish.data, i)) expect(shadeAt(empty.data, i), `${kind} cell ${i / 4}`).toBe(true);
    // The plate sits on the canvas's bottom rows, as the dish does.
    const lastRow = Math.max(...[...Array(dish.h).keys()].filter((y) => empty.data.slice(y * dish.w * 4, (y + 1) * dish.w * 4).some((v, j) => j % 4 === 3 && v > 0)));
    expect(lastRow).toBeGreaterThanOrEqual(dish.h - 8);
  });

  // Value: protects=a dish with no plate of its own (the squid at ×3) still leaves a plate about as wide as the others on
  // stage, and a plated dish's plate keeps its size; fails_when=emptyPlateScale shrinks a plate or grows a plated one
  it.each(dishes)("%s: the empty plate is at least MIN_EMPTY_PLATE_PX wide on stage", (kind) => {
    const { data, w, h } = pixels(kind, drawEmptyPlate);
    const cols = [...Array(w).keys()].filter((x) => [...Array(h).keys()].some((y) => data[(y * w + x) * 4 + 3] > 0));
    const scale = dishScale(kind);
    const shown = emptyPlateScale(kind);
    expect((cols.at(-1)! - cols[0] + 1) * shown).toBeGreaterThanOrEqual(MIN_EMPTY_PLATE_PX);
    if (kind === "dish-squid") expect(shown).toBeGreaterThan(scale);
    if (["dish-tower", "dish-crab", "dish-stew"].includes(kind)) expect(shown).toBe(scale);
  });
});
