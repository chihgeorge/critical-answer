import { describe, expect, it } from "vitest";
import { drawHomeScene, drawSprite, HEAD_ANCHOR, homeSceneCell, SPRITE_SIZE } from "./pixel-art";
import { ACCESSORIES, MONSTERS } from "./monster-catalog";
import type { SpriteKind } from "./sprite-kind";

// A stand-in canvas: drawHomeScene only sets width/height and asks for a 2D context, and returns
// early (no pixels flushed) when there is none, so the layout can be checked without a browser.
const fakeCanvas = () => ({ width: 0, height: 0, getContext: () => null }) as unknown as HTMLCanvasElement;

describe("homeSceneCell", () => {
  it("is a whole number between 4 and 7, so pixels stay square", () => {
    for (const [w, h] of [[320, 568], [390, 844], [820, 1180], [1440, 900], [1920, 800], [3840, 2160]]) {
      const c = homeSceneCell(w, h);
      expect(Number.isInteger(c)).toBe(true);
      expect(c).toBeGreaterThanOrEqual(4);
      expect(c).toBeLessThanOrEqual(7);
    }
  });

  it("is chunkier on a laptop than on a phone", () => {
    expect(homeSceneCell(390, 844)).toBe(5);
    expect(homeSceneCell(1440, 900)).toBe(7);
  });
});

describe("drawHomeScene", () => {
  it.each([[78, 169], [206, 129], [275, 115], [117, 169], [40, 40]])("fits a %i×%i grid and hangs one torch on each side wall", (W, H) => {
    const cv = fakeCanvas();
    const { torches } = drawHomeScene(cv, W, H);
    expect([cv.width, cv.height]).toEqual([W, H]);
    expect(torches).toHaveLength(2);
    for (const t of torches) {
      expect(t.x).toBeGreaterThan(0);
      expect(t.x).toBeLessThan(W);
      expect(t.y).toBeGreaterThan(0);
      expect(t.y).toBeLessThan(H);
    }
    expect(torches[0].x).toBeLessThan(W / 2);
    expect(torches[1].x).toBeGreaterThan(W / 2);
  });

  it("is seeded, so the same size always gives the same scene", () => {
    expect(drawHomeScene(fakeCanvas(), 120, 90)).toEqual(drawHomeScene(fakeCanvas(), 120, 90));
  });
});

// Generated by /ship coverage audit.
// Value: protects=each sprite draws at the size SPRITE_SIZE says (Sprite and DishOnStage size their box from it);
// fails_when=a sprite's Px dims drift from its SPRITE_SIZE row, as the new pot, smoke and dishes could; why_new=no
// test drew sprites; seam=none; no_claim=what the pixels look like (no 2D context in node)
describe("drawSprite", () => {
  it("draws every sprite, in every frame, at its SPRITE_SIZE", () => {
    for (const [kind, [w, h]] of Object.entries(SPRITE_SIZE) as [SpriteKind, [number, number]][]) {
      for (const variant of [0, 1]) {
        const cv = fakeCanvas();
        drawSprite(cv, kind, variant);
        expect([kind, cv.width, cv.height]).toEqual([kind, w, h]);
      }
    }
  });
});

describe("hats on a repeat appearance (docs/designs/monster-catalog.md §3)", () => {
  // Value: protects=every hat, anchored on every room monster's head, stays inside the monster's canvas, and is 8–11 cells wide (R5); fails_when=an anchor or a hat grid grows past the canvas; why_new=new sprites; seam=none; no_claim=how good they look (PNG review)
  it("fits every hat on every room monster", () => {
    for (const m of MONSTERS.filter((x) => !x.boss)) {
      const [mw, mh] = SPRITE_SIZE[m.sprite];
      const [ax, ay] = HEAD_ANCHOR[m.sprite];
      for (const a of ACCESSORIES) {
        const [w, h] = SPRITE_SIZE[`acc-${a}`];
        expect(w, a).toBeGreaterThanOrEqual(8);
        expect(w, a).toBeLessThanOrEqual(11);
        const left = ax - Math.floor(w / 2);
        const top = ay - h + 1;
        expect(left >= 0 && top >= 0 && left + w <= mw && ay <= mh - 1, `${a} on ${m.sprite}`).toBe(true);
      }
    }
  });
});
