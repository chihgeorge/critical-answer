/** A room with one team of `classLabel` and the TV, started; returns once it is the team's turn. */
async function start(browser: Browser, classLabel: string): Promise<{ host: Page; screen: Page; team: Page }> {
  const host = await (await browser.newContext()).newPage();
  await host.goto("/");
  await host.getByRole("button", { name: /主持遊戲/ }).click();
  await host.waitForURL(/\/room\/[A-Z]{4}\/host#k=/);
  const code = host.url().match(/\/room\/([A-Z]{4})\//)![1];
  const screen = await (await browser.newContext({ viewport: { width: 1280, height: 720 } })).newPage();
  await screen.goto(await screenUrl(host));
  const team = await (await browser.newContext({ viewport: { width: 390, height: 844 } })).newPage();
  await team.goto(`/room/${code}/play?name=${encodeURIComponent(`${classLabel}隊`)}`);
  await team.getByRole("button", { name: new RegExp(classLabel) }).click();
  await expect(team.getByRole("button", { name: new RegExp(classLabel) })).toHaveAttribute("aria-pressed", "true");
  await startGame(host);
  await expect(team.getByText("輪到我們了！")).toBeVisible();
  return { host, screen, team };
}
const option = (team: Page, text: string) => team.getByRole("button", { name: new RegExp(`^[A-D]\\s*${text}`) });

test("mage: one press greys out 2 wrong options and spends a use", async ({ browser }) => {
  const { team } = await start(browser, "法師");
  await team.getByRole("button", { name: /刪掉 2 個錯的選項/ }).click();
  await expect(team.getByText("🔮 刪掉了 2 個・剩 3 次")).toBeVisible();
  await expect(option(team, "綠色")).toBeEnabled();
  let out = 0;
  for (const t of ["紅色", "藍色", "黃色"]) if (await option(team, t).isDisabled()) out++;
  expect(out).toBe(2);
  // Generated by /ship coverage audit. Value: protects=a mage's removal greys options with no ✕ 答錯 label (D13=A);
  // fails_when=the label check ignores mageRemoved; why_new=no test read the label; seam=none; no_claim=TV wall label
  await expect(team.getByText("✕ 答錯")).toHaveCount(0);
  await expect(team.getByRole("button", { name: /刪掉 2 個錯的選項/ })).toHaveCount(0);
});

