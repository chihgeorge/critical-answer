import { test, expect } from "@playwright/test";
import "./probe-setup";
import { E2E_OWNER_KEY } from "../playwright.config";

/** A stored bank this version can't read (BankStore's `unreadable`): the editor says so on load and won't save. */
test("an unreadable stored bank loads read-only, with the notice up front and saving disabled", async ({ page }) => {
  let unreadable = true;
  await page.route(/\/api\/bank$/, async (route) => {
    if (route.request().method() !== "GET" || !unreadable) return route.continue();
    const res = await route.fetch();
    await route.fulfill({ response: res, json: { ...(await res.json()), unreadable: true } });
  });
  await page.goto("/bank-editor");
  await page.getByLabel("Owner key").fill(E2E_OWNER_KEY);
  await page.getByRole("button", { name: "載入題庫" }).click();
  await expect(page.getByTestId("bank-editor-readonly")).toBeVisible();
  await expect(page.getByRole("button", { name: "儲存全部變更" })).toBeDisabled();
  if (process.env.SHOT) await page.screenshot({ path: process.env.SHOT });

  // Generated by /ship coverage audit.
  // Value: protects=a later readable load (roll-forward) clears read-only: notice gone, save enabled;
  // fails_when=readOnly is only ever set to true; why_new=the steps above cover only the unreadable load;
  // seam=none; no_claim=a real unreadable Durable Object (GET body route-mocked)
  unreadable = false;
  await page.getByRole("button", { name: "載入題庫" }).click();
  await expect(page.getByTestId("bank-editor-readonly")).toBeHidden();
  await expect(page.getByRole("button", { name: "儲存全部變更" })).toBeEnabled();
});

// Value: protects=an older-format stored bank shows the yellow notice with its format and still lets the owner save over it (the reseed path); fails_when=outdated is treated as read-only or the notice is missing; why_new=new outdated state (monster-catalog.md §5); seam=none; no_claim=a real outdated Durable Object (GET body route-mocked)
test("an outdated stored bank shows the yellow notice and can be saved over", async ({ page }) => {
  await page.route(/\/api\/bank$/, async (route) => {
    if (route.request().method() !== "GET") return route.continue();
    const res = await route.fetch();
    await route.fulfill({ response: res, json: { ...(await res.json()), outdated: 2 } });
  });
  await page.goto("/bank-editor");
  await page.getByLabel("Owner key").fill(E2E_OWNER_KEY);
  await page.getByRole("button", { name: "載入題庫" }).click();
  await expect(page.getByTestId("bank-editor-outdated")).toContainText("格式 2");
  await expect(page.getByTestId("bank-editor-readonly")).toBeHidden();
  await expect(page.getByRole("button", { name: "儲存全部變更" })).toBeEnabled();

  // Generated by /ship coverage audit.
  // Value: protects=saving over the outdated bank (the reseed path) lands and clears the yellow notice; fails_when=the save errors or the notice stays; why_new=the steps above stop at an enabled button; seam=none; no_claim=a real format-2 Durable Object (GET body route-mocked)
  await page.getByRole("button", { name: "儲存全部變更" }).click();
  await expect(page.getByTestId("bank-editor-outdated")).toBeHidden();
  await expect(page.getByTestId("bank-editor-error")).toBeHidden();
});

// Value: protects=mid-deploy, a new editor facing an old Worker (whole monster objects) goes read-only with the red notice instead of showing broken pickers that could save; fails_when=the shape check is dropped; why_new=R3 (D4); seam=none; no_claim=a real old Worker (GET body route-mocked)
test("a bank with whole monster objects (an old server mid-deploy) loads read-only with its own notice", async ({ page }) => {
  await page.route(/\/api\/bank$/, async (route) => {
    if (route.request().method() !== "GET") return route.continue();
    const res = await route.fetch();
    const body = await res.json();
    body.bank.rooms[0].monster = { name: "軟趴趴史萊姆", sprite: "slime", hue: 0 };
    await route.fulfill({ response: res, json: body });
  });
  await page.goto("/bank-editor");
  await page.getByLabel("Owner key").fill(E2E_OWNER_KEY);
  await page.getByRole("button", { name: "載入題庫" }).click();
  await expect(page.getByTestId("bank-editor-stale-server")).toContainText("伺服器還是舊版");
  await expect(page.getByRole("button", { name: "儲存全部變更" })).toBeDisabled();
});
