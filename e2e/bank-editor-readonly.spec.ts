import { test, expect } from "@playwright/test";
import { E2E_OWNER_KEY } from "../playwright.config";

/** A stored bank this version can't read (BankStore's `unreadable`): the editor says so on load and won't save. */
test("an unreadable stored bank loads read-only, with the notice up front and saving disabled", async ({ page }) => {
  let unreadable = true;
  await page.route(/\/api\/bank$/, async (route) => {
    if (route.request().method() !== "GET" || !unreadable) return route.continue();
    const res = await route.fetch();
    await route.fulfill({ response: res, json: { ...(await res.json()), unreadable: true } });
  });
  await page.goto("/bank-editor");
  await page.getByLabel("Owner key").fill(E2E_OWNER_KEY);
  await page.getByRole("button", { name: "載入題庫" }).click();
  await expect(page.getByTestId("bank-editor-readonly")).toBeVisible();
  await expect(page.getByRole("button", { name: "儲存全部變更" })).toBeDisabled();
  if (process.env.SHOT) await page.screenshot({ path: process.env.SHOT });

  // Generated by /ship coverage audit.
  // Value: protects=a later readable load (roll-forward) clears read-only: notice gone, save enabled;
  // fails_when=readOnly is only ever set to true; why_new=the steps above cover only the unreadable load;
  // seam=none; no_claim=a real unreadable Durable Object (GET body route-mocked)
  unreadable = false;
  await page.getByRole("button", { name: "載入題庫" }).click();
  await expect(page.getByTestId("bank-editor-readonly")).toBeHidden();
  await expect(page.getByRole("button", { name: "儲存全部變更" })).toBeEnabled();
});
